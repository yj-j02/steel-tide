export const ARC_EVENTS = RIVAL_ARCS.flatMap((a, ai) => a.steps.map((s, si) => ({ ...s, id: `arc_${a.key}_${si}`, arc: a.key, arcIdx: ai, step: si, last: si === a.steps.length - 1, arcName: a.name })));

/** 내 계급에서 열린 동기 이야기 한 화를 고른다. 없으면 null. */
export function pickRivalArc(rivals = [], grade = 0) {
  for (let ri = 0; ri < Math.min(rivals.length, RIVAL_ARCS.length); ri++) {
    const r = rivals[ri];
    if (!r || r.fate || r.retired) continue;
    const arc = RIVAL_ARCS[ri], step = r.arcStep || 0;
    if (step >= arc.steps.length) continue;
    if (grade >= arc.steps[step].minG) return { evId: `arc_${arc.key}_${step}`, ri };
  }
  return null;
}

/** 이야기 선택 결과를 동기 데이터에 반영한다. */
export function applyArcChoice(r, ev, opt) {
  r.arcStep = (r.arcStep || 0) + 1;
  if (opt.flag) r.arcFlags = [...(r.arcFlags || []), opt.flag];
  if (!opt.fate) return null;
  let f = opt.fate;
  if (f.relGate != null) f = (r.rel ?? 50) >= f.relGate ? f.hi : f.lo;
  if (f.g) r.g = Math.max(0, Math.min(9, (r.g || 0) + f.g));
  if (f.retire) { r.retired = true; r.retiredPost = f.post || r.retiredPost; }
  r.fate = { arc: ev.arcName, note: f.note };
  r.retiredNote = f.note;
  return r.fate;
}
